/**
 * Prisma schema importer for pgweave.
 * Parses a Prisma schema file and generates PostgreSQL DDL + TypeScript types.
 *
 * @example
 * import { fromPrismaSchema } from 'pgweave/plugins/prisma'
 *
 * const { ddl, types } = fromPrismaSchema(schemaContent)
 * // Use ddl as the schema for check/lint, types as TypeScript interfaces
 */

export interface PrismaModel {
  name: string
  tableName: string
  fields: PrismaField[]
}

export interface PrismaField {
  name: string
  columnName: string
  prismaType: string
  pgType: string
  tsType: string
  isOptional: boolean
  isId: boolean
  isUnique: boolean
  default: string | null
}

export interface PrismaParseResult {
  models: PrismaModel[]
  /** PostgreSQL DDL equivalent of the Prisma schema */
  ddl: string
  /** TypeScript interface definitions for all models */
  types: string
}

/**
 * Parse a Prisma schema string and generate PostgreSQL DDL + TypeScript types.
 *
 * Supports:
 * - Model -> table (PascalCase -> snake_case)
 * - Field types: String, Int, BigInt, Float, Boolean, DateTime, Json, Bytes
 * - @id, @unique, @default, @map, @@map
 * - Optional fields (?) -> nullable columns
 */
export function fromPrismaSchema(schemaContent: string): PrismaParseResult {
  const models = parseModels(schemaContent)
  const ddl = generateDdl(models)
  const types = generateTypes(models)
  return { models, ddl, types }
}

// -- Parser -------------------------------------------------------------------

function parseModels(schema: string): PrismaModel[] {
  const models: PrismaModel[] = []
  const modelRegex = /model\s+(\w+)\s*\{([^}]+)\}/g
  let match: RegExpExecArray | null

  while ((match = modelRegex.exec(schema)) !== null) {
    const modelName = match[1]
    const body = match[2]

    // Check for @@map
    const mapMatch = body.match(/@@map\("([^"]+)"\)/)
    const tableName = mapMatch ? mapMatch[1] : toSnakeCase(modelName)

    const fields = parseFields(body)
    models.push({ name: modelName, tableName, fields })
  }

  return models
}

function parseFields(body: string): PrismaField[] {
  const fields: PrismaField[] = []
  const lines = body.split('\n').map(l => l.trim()).filter(l => l && !l.startsWith('@@') && !l.startsWith('//'))

  for (const line of lines) {
    const fieldMatch = line.match(/^(\w+)\s+([\w?]+)(.*)$/)
    if (!fieldMatch) continue

    const fieldName = fieldMatch[1]
    const typeRaw = fieldMatch[2]
    const rest = fieldMatch[3] || ''

    const isOptional = typeRaw.endsWith('?')
    const prismaType = typeRaw.replace('?', '')

    // Skip relation fields (they reference other models — start with uppercase and have no pg equivalent)
    if (/^[A-Z]/.test(prismaType) && !isPrimitivePrismaType(prismaType)) continue

    // Column name from @map
    const mapMatch = rest.match(/@map\("([^"]+)"\)/)
    const columnName = mapMatch ? mapMatch[1] : toSnakeCase(fieldName)

    const isId = rest.includes('@id')
    const isUnique = rest.includes('@unique')

    // Default value
    let defaultVal: string | null = null
    const defaultMatch = rest.match(/@default\(([^)]+)\)/)
    if (defaultMatch) {
      defaultVal = prismaDefaultToPg(defaultMatch[1])
    }

    fields.push({
      name: fieldName,
      columnName,
      prismaType,
      pgType: prismaToPgType(prismaType),
      tsType: prismaToTsType(prismaType),
      isOptional,
      isId,
      isUnique,
      default: defaultVal,
    })
  }

  return fields
}

// -- DDL generator ------------------------------------------------------------

function generateDdl(models: PrismaModel[]): string {
  return models.map(model => {
    const cols = model.fields.map(f => {
      let col = `    ${f.columnName} ${f.pgType}`
      if (f.isId) col += ' PRIMARY KEY'
      else if (f.isUnique) col += ' UNIQUE'
      if (!f.isOptional && !f.isId) col += ' NOT NULL'
      if (f.default) col += ` DEFAULT ${f.default}`
      return col
    })
    return `CREATE TABLE ${model.tableName} (\n${cols.join(',\n')}\n);`
  }).join('\n\n')
}

// -- TypeScript generator -----------------------------------------------------

function generateTypes(models: PrismaModel[]): string {
  const header = '// Generated by pgweave Prisma plugin — do not edit manually\n\n'
  return header + models.map(model => {
    const fields = model.fields.map(f => {
      const opt = f.isOptional ? ' | null' : ''
      return `  ${f.name}: ${f.tsType}${opt};`
    })
    return `export interface ${model.name} {\n${fields.join('\n')}\n}`
  }).join('\n\n')
}

// -- Type maps ----------------------------------------------------------------

function isPrimitivePrismaType(t: string): boolean {
  return ['String', 'Int', 'BigInt', 'Float', 'Boolean', 'DateTime', 'Json', 'Bytes', 'Decimal'].includes(t)
}

function prismaToPgType(t: string): string {
  const map: Record<string, string> = {
    'String': 'TEXT',
    'Int': 'INTEGER',
    'BigInt': 'BIGINT',
    'Float': 'DOUBLE PRECISION',
    'Boolean': 'BOOLEAN',
    'DateTime': 'TIMESTAMPTZ',
    'Json': 'JSONB',
    'Bytes': 'BYTEA',
    'Decimal': 'NUMERIC',
  }
  return map[t] ?? 'TEXT'
}

function prismaToTsType(t: string): string {
  const map: Record<string, string> = {
    'String': 'string',
    'Int': 'number',
    'BigInt': 'bigint',
    'Float': 'number',
    'Boolean': 'boolean',
    'DateTime': 'Date',
    'Json': 'unknown',
    'Bytes': 'Uint8Array',
    'Decimal': 'number',
  }
  return map[t] ?? 'unknown'
}

function prismaDefaultToPg(d: string): string {
  if (d === 'now()') return 'CURRENT_TIMESTAMP'
  if (d === 'autoincrement()') return "nextval('seq')"
  if (d === 'cuid()' || d === 'uuid()') return 'gen_random_uuid()'
  if (d === 'true') return 'TRUE'
  if (d === 'false') return 'FALSE'
  // String default
  if (d.startsWith('"') && d.endsWith('"')) return `'${d.slice(1, -1)}'`
  return d
}

function toSnakeCase(s: string): string {
  return s.replace(/([A-Z])/g, (_, c, i) => (i > 0 ? '_' : '') + c.toLowerCase())
}
