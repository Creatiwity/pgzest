-- Second version: extension and schema, enum value in the middle,
-- added columns, type widened under a view, modified function body,
-- CHECK, row-level security, comments.
CREATE EXTENSION citext;
CREATE SCHEMA audit;

CREATE TYPE order_status AS ENUM ('draft', 'placed', 'cancelled', 'served');

CREATE TABLE customers (
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  email citext NOT NULL UNIQUE,
  name TEXT NOT NULL,
  legacy_code TEXT,
  loyalty INTEGER NOT NULL DEFAULT 0 CHECK (loyalty >= 0),
  owner TEXT NOT NULL DEFAULT current_user
);
ALTER TABLE customers ENABLE ROW LEVEL SECURITY;
CREATE POLICY customers_owner ON customers USING (owner = current_user);
COMMENT ON TABLE customers IS 'Clients';
COMMENT ON COLUMN customers.loyalty IS 'Loyalty points';

CREATE TABLE orders (
  id BIGSERIAL PRIMARY KEY,
  customer_id BIGINT NOT NULL REFERENCES customers (id),
  status order_status NOT NULL DEFAULT 'draft',
  amount BIGINT NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX orders_customer_id ON orders (customer_id);
CREATE INDEX orders_status ON orders (status) WHERE status <> 'served';

CREATE TABLE coupons (
  code TEXT PRIMARY KEY,
  order_id BIGINT REFERENCES orders (id)
);

CREATE TABLE audit.events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES orders (id),
  at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE FUNCTION order_total(o BIGINT) RETURNS INTEGER
LANGUAGE sql STABLE AS $$ SELECT amount::integer FROM orders WHERE id = o $$;

CREATE VIEW order_amounts AS
SELECT o.id, o.amount FROM orders o;

CREATE FUNCTION touch() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END
$$;
CREATE TRIGGER orders_touch BEFORE UPDATE ON orders
FOR EACH ROW EXECUTE FUNCTION touch();
