//! Mapping between two position frames: generated text → source.
//!
//! Used whenever an analyzed text is not the edited text: SQL coming from a
//! macro expansion, a fragment extracted from a `.ts`, preprocessing output.
//!
//! Lives in `pgweave-ast` because that is the crate owning [`crate::Span`]:
//! a mapping between span frames belongs at the same level, and both the
//! parser and the macro expander can access it without knowing each other.
//!
//! The producer copies fragments **verbatim**, so each segment has a
//! constant offset: the mapping is exact, not approximate. Generated text
//! with no antecedent (`CREATE FUNCTION … AS $$` produced by a
//! template) falls back to the nearest preceding copied fragment.

/// A fragment of the generated SQL and its antecedent in the source.
#[derive(Debug, Clone, PartialEq, Eq)]
struct Segment {
    /// Offset of the fragment's start in the generated SQL.
    generated: usize,
    /// Offset of the fragment's start in the `.pgsql`.
    source: usize,
    /// Length of the fragment, in bytes.
    len: usize,
    /// Opaque segment: the generated text is not a copy, it replaces
    /// `Some(n)` bytes of the source (a fragment invocation). No position
    /// in it has an exact antecedent; any range in it is mapped to the
    /// whole invocation.
    opaque: Option<usize>,
}

/// Generated → source mapping.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct SourceMap {
    segments: Vec<Segment>,
}

impl SourceMap {
    pub fn new() -> Self {
        Self::default()
    }

    /// Declares that `len` bytes at `generated` come from `source`.
    pub fn add(&mut self, generated: usize, source: usize, len: usize) {
        if len == 0 {
            return;
        }
        // Merge with the previous segment if contiguous on both sides.
        if let Some(last) = self.segments.last_mut()
            && last.opaque.is_none()
            && last.generated + last.len == generated
            && last.source + last.len == source
        {
            last.len += len;
            return;
        }
        self.segments.push(Segment {
            generated,
            source,
            len,
            opaque: None,
        });
    }

    /// Declares that `len` bytes at `generated` replace the `source_len`
    /// bytes of the source at `source` (text generated by an invocation).
    pub fn add_opaque(&mut self, generated: usize, len: usize, source: usize, source_len: usize) {
        if len == 0 {
            return;
        }
        self.segments.push(Segment {
            generated,
            source,
            len,
            opaque: Some(source_len),
        });
    }

    /// Antecedent of `offset` in the source, if this fragment comes from the source.
    ///
    /// `None` for generated boilerplate, which has no antecedent — the caller
    /// then falls back on [`Self::nearest_source`].
    pub fn to_source(&self, offset: usize) -> Option<usize> {
        let seg = self.segment_at(offset).filter(|s| s.opaque.is_none())?;
        Some(seg.source + (offset - seg.generated))
    }

    /// Antecedent of `offset`, or failing that the start of the nearest
    /// preceding copied segment. Always a usable position for a diagnostic.
    pub fn nearest_source(&self, offset: usize) -> Option<usize> {
        if let Some(exact) = self.to_source(offset) {
            return Some(exact);
        }
        if let Some(seg) = self.segment_at(offset) {
            return Some(seg.source);
        }
        self.segments
            .iter()
            .rev()
            .find(|s| s.generated <= offset)
            .map(|s| s.source + s.len.saturating_sub(1))
            .or_else(|| self.segments.first().map(|s| s.source))
    }

    /// Maps a range of the generated SQL back to the source.
    ///
    /// The start is mapped exactly when it falls in a copied fragment,
    /// otherwise it falls back ([`Self::nearest_source`]). The end is bounded
    /// to the start's segment: a generated range may overlap boilerplate,
    /// in which case extending it to its antecedent would produce an absurd
    /// range in the source.
    pub fn remap(&self, start: usize, end: usize) -> Option<(usize, usize)> {
        let src_start = self.nearest_source(start)?;

        let src_end = match self.segment_at(start) {
            // Start in text generated by an invocation: the invocation.
            Some(Segment {
                opaque: Some(n), ..
            }) => src_start + n,
            // Start in a copied fragment: do not go past its end.
            Some(seg) => {
                let seg_src_end = seg.source + seg.len;
                let projected = src_start + end.saturating_sub(start);
                projected.min(seg_src_end)
            }
            // Start in boilerplate: one-character range, for lack of better.
            None => src_start + 1,
        };

        Some((src_start, src_end.max(src_start)))
    }

    fn segment_at(&self, offset: usize) -> Option<&Segment> {
        // Segments added in increasing `generated` order: binary search
        // on the start.
        let idx = self
            .segments
            .partition_point(|s| s.generated <= offset)
            .checked_sub(1)?;
        let seg = &self.segments[idx];
        (offset < seg.generated + seg.len).then_some(seg)
    }

    pub fn is_empty(&self) -> bool {
        self.segments.is_empty()
    }

    /// Applies `edits` to `text` (the generated text this map describes):
    /// returns the edited text and its map to the same source.
    ///
    /// Untouched text keeps its exact mapping. Inserted text is opaque,
    /// mapped to the antecedent of its edit's `anchor`. Edits must be sorted
    /// by start and must not overlap.
    pub fn apply_edits(&self, text: &str, edits: &[MapEdit]) -> (String, SourceMap) {
        let mut out = String::with_capacity(text.len());
        let mut map = SourceMap::new();
        let mut at = 0usize;
        for edit in edits {
            debug_assert!(edit.range.start >= at, "edits overlap or are unsorted");
            self.copy_piece(at, edit.range.start, &mut out, &mut map, text);
            if let Some((s, e)) = self.remap(edit.anchor.start, edit.anchor.end) {
                map.add_opaque(out.len(), edit.text.len(), s, e - s);
            }
            out.push_str(&edit.text);
            at = edit.range.end;
        }
        self.copy_piece(at, text.len(), &mut out, &mut map, text);
        (out, map)
    }

    /// Copies `text[from..to]` to the end of `out`, with its segments.
    fn copy_piece(
        &self,
        from: usize,
        to: usize,
        out: &mut String,
        map: &mut SourceMap,
        text: &str,
    ) {
        if to <= from {
            return;
        }
        let base = out.len();
        for seg in &self.segments {
            let start = seg.generated.max(from);
            let end = (seg.generated + seg.len).min(to);
            if start >= end {
                continue;
            }
            let generated = base + (start - from);
            match seg.opaque {
                Some(n) => map.add_opaque(generated, end - start, seg.source, n),
                None => map.add(generated, seg.source + (start - seg.generated), end - start),
            }
        }
        out.push_str(&text[from..to]);
    }
}

/// Replacement of `range` of a generated text by `text`; the inserted text
/// is mapped to the source antecedent of `anchor`, a range of the same
/// generated text (the construct it implements).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MapEdit {
    pub range: std::ops::Range<usize>,
    pub text: String,
    pub anchor: std::ops::Range<usize>,
}

impl MapEdit {
    /// Position of `offset` once `edits` (sorted, non-overlapping) are
    /// applied. Text inserted at `offset` lands before it; an offset inside
    /// a replaced range moves to the start of its replacement.
    pub fn shift(edits: &[MapEdit], offset: usize) -> usize {
        let mut delta: isize = 0;
        for e in edits {
            if e.range.end <= offset {
                delta += e.text.len() as isize - e.range.len() as isize;
            } else if e.range.start < offset {
                return (e.range.start as isize + delta) as usize;
            } else {
                break;
            }
        }
        (offset as isize + delta) as usize
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_simple_segment_maps() {
        let mut m = SourceMap::new();
        m.add(100, 10, 5); // generated[100..105] ← source[10..15]
        assert_eq!(m.to_source(100), Some(10));
        assert_eq!(m.to_source(104), Some(14));
        assert_eq!(m.to_source(105), None, "outside the segment");
        assert_eq!(m.to_source(99), None);
    }

    #[test]
    fn contiguous_segments_merge() {
        let mut m = SourceMap::new();
        m.add(0, 50, 10);
        m.add(10, 60, 10); // contiguous on both sides
        assert_eq!(m.segments.len(), 1, "must merge");
        assert_eq!(m.to_source(15), Some(65));
    }

    #[test]
    fn non_contiguous_segments_stay_distinct() {
        let mut m = SourceMap::new();
        m.add(0, 50, 10);
        m.add(10, 200, 10); // same generated, source elsewhere
        assert_eq!(m.segments.len(), 2);
        assert_eq!(m.to_source(5), Some(55));
        assert_eq!(m.to_source(15), Some(205));
    }

    #[test]
    fn several_segments_each_map() {
        let mut m = SourceMap::new();
        m.add(0, 0, 10);
        m.add(30, 100, 10);
        assert_eq!(m.to_source(5), Some(5));
        assert_eq!(m.to_source(35), Some(105));
        assert_eq!(m.to_source(20), None, "boilerplate between the two");
    }

    #[test]
    fn nearest_source_falls_back_on_boilerplate() {
        let mut m = SourceMap::new();
        m.add(0, 0, 10);
        m.add(30, 100, 10);
        // offset 20 = boilerplate: falls back to the end of the previous segment
        assert_eq!(m.nearest_source(20), Some(9));
        assert_eq!(m.nearest_source(5), Some(5), "exact when available");
    }

    #[test]
    fn an_empty_map_maps_nothing() {
        let m = SourceMap::new();
        assert_eq!(m.to_source(0), None);
        assert_eq!(m.nearest_source(0), None);
        assert!(m.is_empty());
    }

    #[test]
    fn a_zero_length_segment_is_ignored() {
        let mut m = SourceMap::new();
        m.add(0, 0, 0);
        assert!(m.is_empty());
    }
}

#[cfg(test)]
mod edit_tests {
    use super::*;

    fn edit(range: std::ops::Range<usize>, text: &str, anchor: std::ops::Range<usize>) -> MapEdit {
        MapEdit {
            range,
            text: text.into(),
            anchor,
        }
    }

    #[test]
    fn untouched_text_keeps_its_exact_mapping() {
        // generated "SELECT a FROM t" ← source[100..115]
        let mut m = SourceMap::new();
        m.add(0, 100, 15);
        let edits = [edit(14..15, "(SELECT 1) AS t", 14..15)];
        let (text, map) = m.apply_edits("SELECT a FROM t", &edits);
        assert_eq!(text, "SELECT a FROM (SELECT 1) AS t");
        assert_eq!(map.to_source(7), Some(107), "`a` is still exact");
        // The replacement is mapped to the replaced name.
        assert_eq!(map.remap(14, 20), Some((114, 115)));
    }

    #[test]
    fn insertions_shift_what_follows() {
        let mut m = SourceMap::new();
        m.add(0, 0, 10);
        let edits = [edit(3..3, "XX", 3..4), edit(6..6, "Y", 6..7)];
        let (text, map) = m.apply_edits("0123456789", &edits);
        assert_eq!(text, "012XX345Y6789");
        assert_eq!(map.to_source(5), Some(3));
        assert_eq!(map.to_source(9), Some(6));
        assert_eq!(MapEdit::shift(&edits, 3), 5, "after the insertion at 3");
        assert_eq!(MapEdit::shift(&edits, 7), 10);
        assert_eq!(MapEdit::shift(&edits, 0), 0);
    }

    #[test]
    fn opaque_segments_stay_opaque() {
        let mut m = SourceMap::new();
        m.add(0, 0, 4);
        m.add_opaque(4, 6, 4, 2); // a fragment call of 2 bytes, 6 generated
        m.add(10, 6, 4);
        let (text, map) = m.apply_edits("abcdFFFFFFwxyz", &[edit(12..12, "!", 12..13)]);
        assert_eq!(text, "abcdFFFFFFwx!yz");
        assert_eq!(
            map.remap(5, 6),
            Some((4, 6)),
            "inside the fragment: its call"
        );
        assert_eq!(map.to_source(13), Some(8));
    }
}

#[cfg(test)]
mod remap_tests {
    use super::*;

    /// generated[100..110] ← source[10..20], the rest being boilerplate.
    fn map() -> SourceMap {
        let mut m = SourceMap::new();
        m.add(100, 10, 10);
        m
    }

    #[test]
    fn an_inner_range_maps_back_exactly() {
        assert_eq!(map().remap(102, 106), Some((12, 16)));
    }

    #[test]
    fn the_end_is_bounded_to_the_segment() {
        // 105..200 goes well beyond the fragment: the end is brought back to its end.
        assert_eq!(map().remap(105, 200), Some((15, 20)));
    }

    #[test]
    fn a_range_in_boilerplate_falls_back() {
        let (start, end) = map().remap(50, 60).expect("rabattu");
        assert!(start <= 20, "must fall back into the source, got {start}");
        assert!(end >= start);
    }

    #[test]
    fn an_empty_map_maps_no_range() {
        assert_eq!(SourceMap::new().remap(0, 5), None);
    }
}
