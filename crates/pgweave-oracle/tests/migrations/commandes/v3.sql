-- Troisième version : colonne et table supprimées, fonction au type de
-- retour changé (vue dépendante reconstruite), vue élargie, trigger et
-- policy modifiés, commentaire retiré, index redéfini, vue matérialisée.
CREATE EXTENSION citext;
CREATE SCHEMA audit;

CREATE TYPE order_status AS ENUM ('draft', 'placed', 'cancelled', 'served');

CREATE TABLE customers (
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  email citext NOT NULL UNIQUE,
  name TEXT NOT NULL,
  loyalty INTEGER NOT NULL DEFAULT 0 CHECK (loyalty >= 0),
  owner TEXT NOT NULL DEFAULT current_user
);
ALTER TABLE customers ENABLE ROW LEVEL SECURITY;
CREATE POLICY customers_owner ON customers FOR SELECT USING (owner = current_user);
COMMENT ON COLUMN customers.loyalty IS 'Points de fidélité';

CREATE TABLE orders (
  id BIGSERIAL PRIMARY KEY,
  customer_id BIGINT NOT NULL REFERENCES customers (id),
  status order_status NOT NULL DEFAULT 'draft',
  amount BIGINT NOT NULL,
  note TEXT,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX orders_customer_id ON orders (customer_id, status);
CREATE INDEX orders_status ON orders (status) WHERE status <> 'served';

CREATE TABLE audit.events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES orders (id),
  at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE FUNCTION order_total(o BIGINT) RETURNS BIGINT
LANGUAGE sql STABLE AS $$ SELECT amount FROM orders WHERE id = o $$;

CREATE VIEW order_amounts AS
SELECT o.id, o.amount, o.status FROM orders o;

CREATE VIEW order_totals AS
SELECT o.id, order_total(o.id) AS total FROM orders o;

CREATE MATERIALIZED VIEW served_per_customer AS
SELECT customer_id, count(*) AS n FROM orders WHERE status = 'served' GROUP BY customer_id;
CREATE INDEX served_per_customer_id ON served_per_customer (customer_id);

CREATE FUNCTION touch() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END
$$;
CREATE TRIGGER orders_touch BEFORE INSERT OR UPDATE ON orders
FOR EACH ROW EXECUTE FUNCTION touch();
