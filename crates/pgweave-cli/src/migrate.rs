//! `pgweave migrate`: migrations generated from the declarative schema
//! (PLAN.md, D10 and P7).
//!
//! The schema (`[schema] declarative = true`) describes the target state; the
//! migrations, the history. `create` compares the state reached by the
//! migrations to the target, writes the migration separating them, and
//! verifies it by replay before writing: the migration replayed after the
//! others must reach exactly the target. `check` reports the gap (CI).

use std::path::{Path, PathBuf};

use pgweave_catalog::ProjectCatalog;
use pgweave_catalog::diff::{Migration, diff};
use pgweave_catalog::project::{ProjectBuilder, parse_source};
use pgweave_diagnostics::{Severity, codes};
use pgweave_schema::{FileRole, ProjectConfig, SchemaSource, SourceOrigin, SqlChunk};

/// Loaded declarative project: configuration, chunks, migrations state and
/// target state.
struct Loaded {
    root: PathBuf,
    config: ProjectConfig,
    chunks: Vec<SqlChunk>,
    macros: pgweave_macro::MacroSet,
    project: ProjectCatalog,
}

fn build(chunks: &[SqlChunk], macros: &pgweave_macro::MacroSet) -> ProjectCatalog {
    let mut b = ProjectBuilder::new()
        .with_typer(Some(pgweave_sema::ViewTyper::shared()))
        .with_checker(Some(pgweave_sema::check::SemaChecker::shared()))
        .declarative(true)
        .keep_sources(true);
    for chunk in chunks {
        let parsed = parse_source(&chunk.sql, chunk.origin.byte_range.start, macros);
        b.add_file(&chunk.origin.path, &chunk.sql, &chunk.role, parsed.as_ref());
    }
    b.finish()
}

/// Errors that make a rebuilt state unusable: unread statement, replay or
/// analysis error.
fn blocking(project: &ProjectCatalog) -> Vec<String> {
    let mut out: Vec<String> = project
        .skipped
        .iter()
        .map(|(p, s)| format!("{}: statement not read ({:?})", p.display(), s.reason))
        .collect();
    out.extend(
        project
            .diagnostics
            .iter()
            .filter(|(_, d)| d.severity == Severity::Error && d.code != codes::SCHEMA_DRIFT)
            .map(|(p, d)| format!("{}: error[{}]: {}", p.display(), d.code, d.message)),
    );
    out
}

fn load() -> Result<Loaded, (i32, String)> {
    let (root, config) = crate::discover_project()
        .map_err(|e| (2, e))?
        .ok_or_else(|| (2, format!("no {} found", ProjectConfig::FILENAME)))?;
    if !config.schema.declarative {
        return Err((
            2,
            "the project is not declarative: `pgweave migrate` generates migrations from the \
             schema when `[schema] declarative = true` (the schema then describes the full state)"
                .into(),
        ));
    }
    let (macros, macro_errors) = crate::load_macros(Some(&(root.clone(), config.clone())));
    if !macro_errors.is_empty() {
        return Err((2, macro_errors.join("\n")));
    }
    let chunks: Vec<SqlChunk> = config
        .to_source(&root)
        .chunks()
        .into_iter()
        .filter(|c| c.role != FileRole::Query)
        .collect();
    let project = build(&chunks, &macros);
    let errors = blocking(&project);
    if !errors.is_empty() {
        return Err((
            1,
            format!(
                "rebuilt state incomplete or in error, no migration can be derived from it:\n{}",
                errors.join("\n")
            ),
        ));
    }
    Ok(Loaded {
        root,
        config,
        chunks,
        macros,
        project,
    })
}

fn history_and_target(l: &Loaded) -> Migration {
    let history = l
        .project
        .history
        .as_ref()
        .expect("declarative project: replayed history");
    diff(history, &l.project.catalog)
}

// ── Rendering ─────────────────────────────────────────────────────────────────

fn print_unsupported(m: &Migration) {
    for u in &m.unsupported {
        eprintln!("to write: {}: {}", u.object, u.change);
    }
}

/// Migration text: context header, what to review or write, notes, then
/// each statement preceded by its risks.
///
/// The generated migration is the simplest one that reaches the schema: it
/// may lose data or fail on a populated database. Only the developer knows
/// the data; the header tells them what to adapt.
fn render(m: &Migration, header: &str, name: &str) -> String {
    let mut out =
        format!("{header}\n-- Migration \"{name}\", generated by `pgweave migrate create`.\n");
    let review: Vec<_> = m
        .steps
        .iter()
        .flat_map(|s| s.risks.iter().filter(|r| r.needs_review()))
        .collect();
    if !review.is_empty() || !m.unsupported.is_empty() {
        out.push_str(
            "--\n-- !! TO ADAPT before applying: migration generated in the simplest way, it\n\
             -- !! reaches the schema but may lose data or fail on a populated\n\
             -- !! database. `pgweave migrate check` verifies the final state after adapting.\n",
        );
        for r in &review {
            out.push_str(&format!("-- !! - {}: {}\n", r.code, r.message));
        }
        for u in &m.unsupported {
            out.push_str(&format!("-- !! - TO WRITE, {}: {}\n", u.object, u.change));
        }
    }
    for n in &m.notes {
        out.push_str(&format!("-- note: {n}\n"));
    }
    if !m.unsupported.is_empty() {
        out.push_str("\n-- TO WRITE: changes pgweave does not generate.\n");
        for u in &m.unsupported {
            out.push_str(&format!("-- TODO {}: {}\n", u.object, u.change));
        }
    }
    for step in &m.steps {
        out.push('\n');
        for r in &step.risks {
            out.push_str(&format!("-- !! {}: {}\n", r.code, r.message));
        }
        out.push_str(&step.sql);
        out.push('\n');
    }
    out
}

// ── Location ──────────────────────────────────────────────────────────────────

/// Directory layout, read from the existing migrations.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Layout {
    Flat,
    Prisma,
    Diesel,
}

fn layout(chunks: &[SqlChunk]) -> Layout {
    let named = |n: &str| {
        chunks.iter().any(|c| {
            matches!(c.role, FileRole::Migration { .. })
                && c.origin.path.file_name().is_some_and(|f| f == n)
        })
    };
    if named("migration.sql") {
        Layout::Prisma
    } else if named("up.sql") {
        Layout::Diesel
    } else {
        Layout::Flat
    }
}

/// Numeric prefix of a name (`0003_x` → `0003`).
fn digits(stem: &str) -> &str {
    let end = stem
        .find(|c: char| !c.is_ascii_digit())
        .unwrap_or(stem.len());
    &stem[..end]
}

fn migration_path(dir: &Path, chunks: &[SqlChunk], name: &str) -> PathBuf {
    let now = chrono::Utc::now();
    match layout(chunks) {
        Layout::Prisma => dir
            .join(format!("{}_{name}", now.format("%Y%m%d%H%M%S")))
            .join("migration.sql"),
        Layout::Diesel => dir
            .join(format!("{}_{name}", now.format("%Y-%m-%d-%H%M%S")))
            .join("up.sql"),
        Layout::Flat => {
            // Numbering of the existing migrations: a short counter (`0007`)
            // is continued, a timestamp otherwise.
            let prefixes: Vec<&str> = chunks
                .iter()
                .filter(|c| matches!(c.role, FileRole::Migration { .. }))
                .filter_map(|c| c.origin.path.file_stem().and_then(|s| s.to_str()))
                .map(digits)
                .filter(|d| !d.is_empty())
                .collect();
            let width = prefixes.iter().map(|d| d.len()).max().unwrap_or(4);
            let prefix = if width <= 6 {
                let next = prefixes
                    .iter()
                    .filter_map(|d| d.parse::<u64>().ok())
                    .max()
                    .map_or(1, |n| n + 1);
                format!("{next:0width$}")
            } else {
                now.format("%Y%m%d%H%M%S").to_string()
            };
            dir.join(format!("{prefix}_{name}.sql"))
        }
    }
}

// ── Commands ──────────────────────────────────────────────────────────────────

pub fn create(name: &str, dry_run: bool) -> i32 {
    if name.is_empty()
        || !name
            .chars()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
    {
        eprintln!("error: migration name expected in lowercase, digits and `_`: \"{name}\"");
        return 2;
    }
    let l = match load() {
        Ok(l) => l,
        Err((code, e)) => {
            eprintln!("error: {e}");
            return code;
        }
    };
    let m = history_and_target(&l);
    if m.is_empty() {
        println!("no change: the migrations already reach the declarative schema");
        return 0;
    }

    let header = pgweave_catalog::dump::header(&l.project.catalog, l.config.postgres.version);
    let sql = render(&m, &header, name);
    let dir = l.root.join(&l.config.migrations.directory);
    let path = migration_path(&dir, &l.chunks, name);

    // Verification: the migration replayed after the others reaches the
    // target, without error.
    let sequence = l
        .chunks
        .iter()
        .filter_map(|c| match c.role {
            FileRole::Migration { sequence } => Some(sequence),
            _ => None,
        })
        .max()
        .map_or(1, |s| s + 1);
    let mut chunks = l.chunks.clone();
    let insert_at = chunks
        .iter()
        .position(|c| !matches!(c.role, FileRole::Migration { .. }))
        .unwrap_or(chunks.len());
    chunks.insert(
        insert_at,
        SqlChunk {
            origin: SourceOrigin {
                path: path.clone(),
                byte_range: 0..sql.len(),
            },
            sql: sql.clone(),
            role: FileRole::Migration { sequence },
        },
    );
    let verified = build(&chunks, &l.macros);
    let errors = blocking(&verified);
    let rest = diff(
        verified.history.as_ref().expect("declarative project"),
        &verified.catalog,
    );
    // Only the changes left to write by hand remain: everything else is reached.
    if !errors.is_empty() || !rest.steps.is_empty() || rest.unsupported != m.unsupported {
        eprintln!("error: the generated migration fails its replay verification (pgweave defect):");
        for e in &errors {
            eprintln!("  {e}");
        }
        if !rest.is_empty() {
            eprintln!("  remaining gap:\n{}", rest.to_sql());
        }
        eprintln!("--- migration\n{sql}");
        return 1;
    }

    for step in &m.steps {
        for r in &step.risks {
            eprintln!("warning[{}]: {}", r.code, r.message);
        }
    }
    print_unsupported(&m);
    for n in &m.notes {
        eprintln!("note: {n}");
    }
    if dry_run {
        print!("{sql}");
        return 0;
    }
    let written = path
        .parent()
        .map_or(Ok(()), std::fs::create_dir_all)
        .and_then(|_| std::fs::write(&path, &sql));
    if let Err(e) = written {
        eprintln!("error: {}: {e}", path.display());
        return 2;
    }
    let shown = path.strip_prefix(&l.root).unwrap_or(&path).display();
    println!(
        "written: {shown} ({} statement(s), verified by replay)",
        m.steps.len()
    );
    if m.steps
        .iter()
        .any(|s| s.risks.iter().any(|r| r.needs_review()))
    {
        println!("to adapt: see the \"TO ADAPT\" header of {shown} before applying it");
    }
    if !m.unsupported.is_empty() {
        println!(
            "to complete: {} change(s) to write in {shown}; `pgweave migrate check` fails until then",
            m.unsupported.len()
        );
    }
    0
}

pub fn check() -> i32 {
    let l = match load() {
        Ok(l) => l,
        Err((code, e)) => {
            eprintln!("error: {e}");
            return code;
        }
    };
    let m = history_and_target(&l);
    if m.is_empty() {
        println!("up to date: the migrations reach the declarative schema");
        return 0;
    }
    eprintln!(
        "error: the declarative schema differs from the migrations ({} statement(s) to generate):",
        m.steps.len()
    );
    for step in &m.steps {
        eprintln!("  {}", step.sql.lines().next().unwrap_or_default());
    }
    print_unsupported(&m);
    if m.steps.is_empty() {
        eprintln!("hint: these changes are written by hand in a migration");
    } else {
        eprintln!("hint: `pgweave migrate create <name>` generates the migration");
    }
    1
}

/// Statements of a SQL file, or of the `.sql` files of a directory (path
/// order), replayed.
fn replay_path(path: &str) -> Result<ProjectCatalog, String> {
    let p = Path::new(path);
    let mut files = Vec::new();
    if p.is_dir() {
        let mut stack = vec![p.to_path_buf()];
        while let Some(d) = stack.pop() {
            for e in std::fs::read_dir(&d).map_err(|e| format!("{}: {e}", d.display()))? {
                let e = e.map_err(|e| e.to_string())?.path();
                if e.is_dir() {
                    stack.push(e);
                } else if e.extension().is_some_and(|x| x == "sql") {
                    files.push(e);
                }
            }
        }
        files.sort();
    } else {
        files.push(p.to_path_buf());
    }
    let mut b = ProjectBuilder::new()
        .with_typer(Some(pgweave_sema::ViewTyper::shared()))
        .keep_sources(true);
    let macros = pgweave_macro::MacroSet::builtin();
    for f in &files {
        let sql = std::fs::read_to_string(f).map_err(|e| format!("{}: {e}", f.display()))?;
        let parsed = parse_source(&sql, 0, &macros);
        b.add_file(f, &sql, &FileRole::Schema, parsed.as_ref());
    }
    let project = b.finish();
    let errors = blocking(&project);
    if !errors.is_empty() {
        return Err(errors.join("\n"));
    }
    Ok(project)
}

/// `migrate diff old new`: migration between two schemas (files or
/// directories), without a project.
pub fn diff_files(old: &str, new: &str) -> i32 {
    let (before, after) = match (replay_path(old), replay_path(new)) {
        (Ok(a), Ok(b)) => (a, b),
        (Err(e), _) | (_, Err(e)) => {
            eprintln!("error: {e}");
            return 1;
        }
    };
    let m = diff(&before.catalog, &after.catalog);
    if m.is_empty() {
        println!("-- no change");
        return 0;
    }
    let header =
        pgweave_catalog::dump::header(&after.catalog, pgweave_catalog::project::DEFAULT_POSTGRES);
    print!("{}", render(&m, &header, "diff"));
    print_unsupported(&m);
    if m.unsupported.is_empty() { 0 } else { 1 }
}
