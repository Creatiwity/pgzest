//! Reference pages of the documentation site generated from the code
//! (PLAN.md P10): the CLI reference from the binary's own `--help`, the
//! diagnostics reference from the documented code constants. `--check`
//! fails when a page is stale, or when a diagnostic code is written as a
//! literal instead of a documented constant.

use std::path::{Path, PathBuf};
use std::process::Command;

const SITE_REFERENCE: &str = "site/src/content/docs/reference";
const NOTICE: &str = "<!-- Generated by `cargo xtask docs` from the code: do not edit. -->";

pub fn run(check: bool) -> Result<(), String> {
    let root = workspace_root();
    let mut problems = literal_codes(&root)?;
    let pages = [
        ("cli.md", cli_reference(&root)?),
        ("diagnostics.md", diagnostics_reference(&root)?),
    ];
    for (name, content) in pages {
        let path = root.join(SITE_REFERENCE).join(name);
        if check {
            let current = std::fs::read_to_string(&path).unwrap_or_default();
            if current != content {
                problems.push(format!(
                    "{} is stale: run `cargo xtask docs`",
                    path.strip_prefix(&root).unwrap_or(&path).display()
                ));
            }
        } else {
            std::fs::create_dir_all(path.parent().expect("reference directory"))
                .map_err(|e| e.to_string())?;
            std::fs::write(&path, content).map_err(|e| format!("{}: {e}", path.display()))?;
            println!(
                "written: {}",
                path.strip_prefix(&root).unwrap_or(&path).display()
            );
        }
    }
    if problems.is_empty() {
        Ok(())
    } else {
        Err(problems.join("\n"))
    }
}

fn workspace_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("xtask lives in the workspace")
        .to_path_buf()
}

// ── CLI ──────────────────────────────────────────────────────────────────────

/// `pgzest <args> --help`, built from the workspace, without the
/// environment the help would show (`[env: DATABASE_URL=…]`).
fn help(root: &Path, args: &[&str]) -> Result<String, String> {
    let out = Command::new(env!("CARGO"))
        .args(["run", "-q", "-p", "pgzest", "--"])
        .args(args)
        .arg("--help")
        .env_remove("DATABASE_URL")
        .env("COLUMNS", "100")
        .current_dir(root)
        .output()
        .map_err(|e| format!("cargo run: {e}"))?;
    if !out.status.success() {
        return Err(format!(
            "pgzest {} --help: {}",
            args.join(" "),
            String::from_utf8_lossy(&out.stderr)
        ));
    }
    Ok(String::from_utf8_lossy(&out.stdout).trim_end().to_string())
}

/// The subcommands a help text lists, `help` left out.
fn subcommands(help: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut inside = false;
    for line in help.lines() {
        if line.starts_with("Commands:") {
            inside = true;
            continue;
        }
        if inside {
            if !line.starts_with("  ") {
                break;
            }
            if let Some(name) = line.split_whitespace().next()
                && name != "help"
            {
                out.push(name.to_string());
            }
        }
    }
    out
}

fn cli_reference(root: &Path) -> Result<String, String> {
    let mut out = format!(
        "---\ntitle: \"CLI reference\"\ndescription: \"Every pgzest command and option, as \
         `pgzest --help` prints them.\"\n---\n\n{NOTICE}\n\nEvery command, with its help as \
         the binary prints it.\n"
    );
    let top = help(root, &[])?;
    out.push_str(&format!("\n## `pgzest`\n\n```text\n{top}\n```\n"));
    let mut stack: Vec<Vec<String>> = subcommands(&top)
        .into_iter()
        .rev()
        .map(|c| vec![c])
        .collect();
    while let Some(path) = stack.pop() {
        let args: Vec<&str> = path.iter().map(String::as_str).collect();
        let text = help(root, &args)?;
        out.push_str(&format!(
            "\n## `pgzest {}`\n\n```text\n{text}\n```\n",
            path.join(" ")
        ));
        for sub in subcommands(&text).into_iter().rev() {
            let mut p = path.clone();
            p.push(sub);
            stack.push(p);
        }
    }
    Ok(out)
}

// ── Diagnostics ──────────────────────────────────────────────────────────────

/// A documented code constant.
struct Code {
    code: String,
    doc: String,
}

/// The `/// doc` + `pub const NAME: &str = "code";` pairs of a file, under
/// its `// ── Section ──` titles. A constant without documentation is an
/// error: the reference would list it unexplained.
fn constants(path: &Path) -> Result<Vec<(String, Vec<Code>)>, String> {
    let text = std::fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))?;
    let mut sections: Vec<(String, Vec<Code>)> = vec![(String::new(), Vec::new())];
    let mut doc: Vec<String> = Vec::new();
    for line in text.lines() {
        let t = line.trim();
        if let Some(title) = t.strip_prefix("// ── ") {
            let title = title.trim_end_matches(['─', ' ']);
            sections.push((title.to_string(), Vec::new()));
            doc.clear();
        } else if let Some(d) = t.strip_prefix("///") {
            doc.push(d.trim().to_string());
        } else if let Some(rest) = t.strip_prefix("pub const ")
            && let Some((name, value)) = rest.split_once(": &str = \"")
        {
            let code = value.trim_end_matches("\";").to_string();
            // Settings, channels, SQL: not diagnostic codes.
            let is_code = !code.is_empty()
                && code
                    .chars()
                    .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-' || c == '/')
                || (code.len() == 4
                    && code.starts_with(|c: char| c.is_ascii_uppercase())
                    && code[1..].chars().all(|c| c.is_ascii_digit()));
            if !is_code {
                doc.clear();
                continue;
            }
            if doc.is_empty() {
                return Err(format!(
                    "{}: `{name}` ({code}) has no documentation",
                    path.display()
                ));
            }
            sections.last_mut().expect("a section").1.push(Code {
                code,
                doc: doc.join(" "),
            });
            doc.clear();
        } else if !t.starts_with("#[") {
            doc.clear();
        }
    }
    sections.retain(|(_, codes)| !codes.is_empty());
    Ok(sections)
}

/// The lint rules: code and description from each rule's leading
/// `/// L00x — summary` documentation.
fn lint_rules(root: &Path) -> Result<Vec<Code>, String> {
    let dir = root.join("crates/pgzest-lint/src/rules");
    let mut files: Vec<PathBuf> = std::fs::read_dir(&dir)
        .map_err(|e| format!("{}: {e}", dir.display()))?
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.extension().is_some_and(|e| e == "rs") && !p.ends_with("mod.rs"))
        .collect();
    files.sort();
    let mut out = Vec::new();
    for f in files {
        let text = std::fs::read_to_string(&f).map_err(|e| e.to_string())?;
        let doc: Vec<&str> = text
            .lines()
            .take_while(|l| l.starts_with("///"))
            .map(|l| l.trim_start_matches('/').trim())
            .collect();
        let (code, summary) = doc
            .first()
            .and_then(|l| l.split_once(" — "))
            .ok_or_else(|| format!("{}: no leading `/// Lxxx — summary`", f.display()))?;
        let rest: Vec<&str> = doc[1..]
            .iter()
            .copied()
            .skip_while(|l| l.is_empty())
            .take_while(|l| !l.is_empty())
            .collect();
        let summary = summary.trim_end_matches('.');
        let doc = if rest.is_empty() {
            format!("{summary}.")
        } else {
            format!("{summary}. {}", rest.join(" "))
        };
        out.push(Code {
            code: code.to_string(),
            doc,
        });
    }
    out.sort_by(|a, b| a.code.cmp(&b.code));
    Ok(out)
}

fn table(codes: &[Code]) -> String {
    let mut out = String::from("| Code | Meaning |\n|------|---------|\n");
    for c in codes {
        out.push_str(&format!(
            "| `{}` | {} |\n",
            c.code,
            c.doc.replace('|', "\\|")
        ));
    }
    out
}

fn diagnostics_reference(root: &Path) -> Result<String, String> {
    let mut out = format!(
        "---\ntitle: \"Diagnostics\"\ndescription: \"Every diagnostic code pgzest reports, and \
         what it means.\"\n---\n\n{NOTICE}\n\nEvery diagnostic carries a code: the one to name in \
         `[rules]` of `pgzest.toml` to change its severity, or in a `-- pgzest-disable-next-line \
         <code>` comment to silence it at one place.\n"
    );
    for (title, codes) in constants(&root.join("crates/pgzest-diagnostics/src/codes.rs"))? {
        out.push_str(&format!("\n## {title}\n\n{}", table(&codes)));
    }
    let macros: Vec<Code> = [
        "crates/pgzest-macro/src/expand.rs",
        "crates/pgzest-macro/src/instrument.rs",
    ]
    .iter()
    .map(|f| constants(&root.join(f)))
    .collect::<Result<Vec<_>, _>>()?
    .into_iter()
    .flatten()
    .flat_map(|(_, c)| c)
    .collect();
    out.push_str(&format!("\n## Macros\n\n{}", table(&macros)));
    let risks: Vec<Code> = constants(&root.join("crates/pgzest-catalog/src/diff.rs"))?
        .into_iter()
        .flat_map(|(_, c)| c)
        .filter(|c| c.code.starts_with('M'))
        .collect();
    out.push_str(&format!(
        "\n## Migration risks\n\nReported on the statements of a generated migration \
         (`pgzest migrate create`), and listed in its `!! TO ADAPT` header when the \
         migration may lose data or fail on a populated database.\n\n{}",
        table(&risks)
    ));
    out.push_str(&format!(
        "\n## Lint\n\nStyle and practice rules (`pgzest lint`).\n\n{}",
        table(&lint_rules(root)?)
    ));
    let rls: Vec<Code> = constants(&root.join("crates/pgzest-plugin/src/builtin/rls_enforcer.rs"))?
        .into_iter()
        .flat_map(|(_, c)| c)
        .collect();
    out.push_str(&format!(
        "\n## Plugin `rls-enforcer`\n\nEnabled by `[plugins] builtin = {{ rls-enforcer = {{}} \
         }}`.\n\n{}",
        table(&rls)
    ));
    Ok(out)
}

/// Diagnostics built with a literal code (`Diagnostic::error("x", …)`):
/// the code escapes the reference.
fn literal_codes(root: &Path) -> Result<Vec<String>, String> {
    let out = Command::new("git")
        .args(["ls-files", "crates/*/src/*.rs", "crates/*/src/**/*.rs"])
        .current_dir(root)
        .output()
        .map_err(|e| format!("git ls-files: {e}"))?;
    let mut problems = Vec::new();
    for file in String::from_utf8_lossy(&out.stdout).lines() {
        let text = std::fs::read_to_string(root.join(file)).map_err(|e| e.to_string())?;
        for pattern in [
            "Diagnostic::error(",
            "Diagnostic::warning(",
            "Diagnostic::info(",
            "SemaError::new(",
        ] {
            let mut rest = text.as_str();
            while let Some(i) = rest.find(pattern) {
                let after = rest[i + pattern.len()..].trim_start();
                if after.starts_with('"') {
                    let line = text[..text.len() - rest.len() + i].lines().count();
                    problems.push(format!(
                        "{file}:{line}: diagnostic code written as a literal: declare a documented \
                         constant (pgzest-diagnostics/src/codes.rs)"
                    ));
                }
                rest = &rest[i + pattern.len()..];
            }
        }
    }
    Ok(problems)
}
